#!/usr/bin/env python3
"""Generates Surface.g.cs from ../ref/System.Printing.cs.

The reference file is the public API contract. Every member keeps its signature; bodies that say `throw null`
become PlatformNotSupportedException so an unimplemented member fails loudly instead of returning null. Members
implemented by hand in the *.cs files next to this script are listed in IMPLEMENTED and removed from the output
(the types are `partial`, so the hand-written side supplies them).
"""
import re
import sys
from pathlib import Path

here = Path(__file__).resolve().parent
src = (here.parent / "ref" / "System.Printing.cs").read_text(encoding="utf-8-sig")

# (type name, regex matching the member line) -> member implemented by hand.
IMPLEMENTED = {
    "PrintSystemObject": [r"string Name \{", r"PrintSystemObject\(\)", r"PrintSystemObject\(System.Printing.PrintSystemObjectLoadMode"],
    "PrintServer": [r"PrintServer\(", r"GetPrintQueues\(", r"override void (Commit|Refresh)\(\)", r"string Name"],  # Name: sealed override in PrintServer.cs
    "LocalPrintServer": [r"LocalPrintServer\(", r"DefaultPrintQueue", r"GetDefaultPrintQueue\(", r"override void (Commit|Refresh)\(\)"],
    "PrintQueue": [r"PrintQueue\(System.Printing.PrintServer", r"string (FullName|Description|Comment|Location)\b",
                   r"PrintServer HostingPrintServer", r"string Name\b", r"override void (Commit|Refresh)\(\)", r"bool IsOffline",
                   r"PrintJobSettings CurrentJobSettings",
                   r"XpsDocumentWriter CreateXpsDocumentWriter\(System.Printing.PrintQueue printQueue\)", r"PrintTicket (DefaultPrintTicket|UserPrintTicket)\b", r"GetPrintCapabilities(AsXml)?\(", r"MergeAndValidatePrintTicket\("],
    "PrintJobSettings": [r"PrintTicket CurrentPrintTicket", r"string Description"],
    "XpsDocumentWriter": [r"XpsDocumentWriter\(", r"void Write\(",
                          r"event System.Windows.Documents.Serialization.WritingPrintTicketRequiredEventHandler WritingPrintTicketRequired",
                          r"raise_WritingPrintTicketRequired\("],
    "PrintQueueCollection": [r"PrintQueueCollection\(", r"void Add\(", r"GetEnumerator\(\)", r"GetNonGenericEnumerator\(\)", r"SyncRoot"],
}

out = []
current = None
for line in src.splitlines():
    m = re.match(r"\s*(?:public|internal)\s+(?:sealed |abstract |static )*partial class (\w+)", line)
    if m:
        current = m.group(1)
    elif re.match(r"\s*(?:public|internal)\s+(?:sealed |abstract |static )*(?:enum|interface|struct) ", line):
        current = None
    if current in IMPLEMENTED and line.startswith("        ") and any(re.search(p, line) for p in IMPLEMENTED[current]):
        continue
    line = line.replace("{ throw null; }", '{ throw new System.PlatformNotSupportedException("Not implemented by the managed System.Printing."); }')
    line = re.sub(r"\bget \{ throw null; \}", 'get { throw new System.PlatformNotSupportedException("Not implemented by the managed System.Printing."); }', line)
    throw = 'throw new System.PlatformNotSupportedException("Not implemented by the managed System.Printing.");'
    line = line.replace("set { }", "set { " + throw + " }")
    method = re.search(r"\b(\w+)\([^)]*\) \{ \}$", line)
    if method and current and line.startswith("        ") and method.group(1) not in ("Dispose", "InternalDispose", "Initialize") and method.group(1) != current and "~" not in line and "protected " + current + "(" not in line:
        line = line[: line.rindex("{ }")] + "{ " + throw + " }"
    out.append(line)

header = "// <auto-generated> by generate-surface.py from ../ref/System.Printing.cs; do not edit. </auto-generated>\n#pragma warning disable CS0067, CS0108, CS0114, CS0626, CS8618, CS8625\n"
Path(sys.argv[1] if len(sys.argv) > 1 else here / "Surface.g.cs").write_text(header + "\n".join(out) + "\n", encoding="utf-8")
